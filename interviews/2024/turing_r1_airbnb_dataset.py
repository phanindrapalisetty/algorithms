"""
What is the average price difference between a professional host and a non-professional one?
Consider a host as professional if they have listings in more than 5 different locations (location is defined by the 'neighbourhood_cleansed' column).
"""

df = listings[['host_id', 'host_is_superhost','neighbourhood_cleansed','price', 'host_location']]

df.head()

df_group = df.groupby('host_id')['neighbourhood_cleansed'].count().reset_index()

df_group.rename(columns={
    'neighbourhood_cleansed': 'number_loc'
}, inplace=True)

df = pd.merge(df, df_group, left_on='host_id', right_on='host_id', how='left')

df.head()

df['is_professional_host'] = df['number_loc'].apply(lambda x: 'yes' if x>5 else 'no')

df['price'] = df['price'].apply(lambda x: x.replace('$', '').replace(',', ''))
df['price'] = df['price'].astype('float')

df_result = df.groupby('is_professional_host')['price'].mean().reset_index()

df_result

